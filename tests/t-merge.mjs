// 3-way merge of device and Drive data (sync.js); no browser needed.
import fs from 'node:fs'; import vm from 'node:vm';
const ctx = { window: {} }; vm.createContext(ctx);
vm.runInContext(fs.readFileSync(new URL('../sync.js', import.meta.url), 'utf8'), ctx);
const { merge, fingerprint, same } = ctx.window.CFSync;
const C = o => JSON.parse(JSON.stringify(o));
let n = 0; const ok = (c, m) => { if (!c) { console.log('✗ FAIL:', m); process.exit(1); } n++; console.log('  ✓', m); };
const T = (id, extra = {}) => Object.assign({ id, accountId: 'a1', date: '2026-09-01', amount: 100, type: 'debit', category: 'Food', desc: id }, extra);
const base = { version: 2, profiles: [{ id: 'p1', name: 'Me' }], accounts: [{ id: 'a1', profileId: 'p1', name: 'HDFC' }], statements: [], txns: [T('t1'), T('t2'), T('t3')], categories: [{ name: 'Food' }], rules: { swiggy: 'Food' } };
const B = fingerprint(base);
const ids = d => d.txns.map(t => t.id).sort().join(',');

let L = C(base), R = C(base);
L.txns.push(T('t4')); R.txns.push(T('t5'));
let m = merge(L, R, B, true);
ok(ids(m) === 't1,t2,t3,t4,t5', 'new transactions on both devices are all kept');
L = C(base); R = C(base); L.txns = L.txns.filter(t => t.id !== 't2');
ok(ids(merge(L, R, B, true)) === 't1,t3', 'deleted here, unchanged there → deleted');
ok(ids(merge(R, L, B, false)) === 't1,t3', 'deleted there, unchanged here → deleted');
L = C(base); R = C(base); L.txns = L.txns.filter(t => t.id !== 't2'); R.txns[1].category = 'Shopping';
m = merge(L, R, B, true);
ok(ids(m) === 't1,t2,t3' && m.txns.find(t => t.id === 't2').category === 'Shopping', 'deleted here but edited there → edit kept');
L = C(base); R = C(base); L.txns[0].category = 'Rent';
ok(merge(L, R, B, false).txns[0].category === 'Rent', 'edited only here → kept even when the remote copy is newer');
L = C(base); R = C(base); R.txns[0].category = 'Travel';
ok(merge(L, R, B, true).txns[0].category === 'Travel', 'edited only there → taken even when this device is newer');
L = C(base); R = C(base); L.txns[0].category = 'Rent'; R.txns[0].category = 'Travel';
ok(merge(L, R, B, true).txns[0].category === 'Rent' && merge(L, R, B, false).txns[0].category === 'Travel', 'edited on both → newer edit wins');
L = C(base); R = C(base); L.rules.zomato = 'Food'; R.rules.uber = 'Transport'; delete R.rules.swiggy;
m = merge(L, R, B, true);
ok(m.rules.zomato && m.rules.uber && !m.rules.swiggy, 'merchant rules merge per merchant (adds both, delete sticks)');
L = C(base); R = C(base); L.categories.push({ name: 'Pets' });
ok(merge(L, R, B, false).categories.length === 2, 'category list changed only here → kept');
L = C(base); R = C(base); R.accounts = []; R.txns = [];
m = merge(L, R, B, true);
ok(m.accounts.length === 0 && m.txns.length === 0, 'account deleted on other device → its transactions go too');
L = C(base); L.txns.push(T('t9')); R = C(base); R.accounts = []; R.txns = [];
m = merge(L, R, B, true);
ok(m.accounts.length === 0 && m.txns.length === 0, 'new txn for an account deleted elsewhere is dropped (no orphans)');
L = C(base); R = C(base); L.txns.push(T('tX')); R.txns.push(T('tX'));
ok(merge(L, R, B, true).txns.filter(t => t.id === 'tX').length === 1, 'same statement imported on both devices → no duplicates');
L = C(base); R = { version: 2, profiles: [{ id: 'p9', name: 'Old' }], accounts: [], statements: [], txns: [], categories: [], rules: {} };
m = merge(L, R, null, true);
ok(m.profiles.length === 2 && ids(m) === 't1,t2,t3', 'never synced (no base) → union, nothing deleted');
L = C(base); L.txns = [];
m = merge(L, C(base), B, true);
ok(m.txns.length === 0, '"Delete all data" here (remote unchanged) → deleted everywhere');
const r = C(base); r.txns.reverse(); r.profiles = C(base.profiles);
ok(same(base, r) && !same(base, merge(C(base), Object.assign(C(base), { txns: [] }), B, true)), 'same() ignores order, detects real changes');
ok(merge(C(base), null, B, true).txns.length === 3 && merge(null, C(base), B, true).txns.length === 3, 'one side missing → the other side');
console.log(`\n${n} merge checks passed`);
