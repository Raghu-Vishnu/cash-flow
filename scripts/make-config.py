#!/usr/bin/env python3
"""Write config.js (the browser's settings) from environment variables.

Values come from real environment variables first (GitHub Actions passes the repository
variable this way), then from the local .env file. config.js is generated, so it is never
committed. Run from anywhere:  python3 scripts/make-config.py
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CLIENT_ID_RE = re.compile(r'^[0-9]+-[a-z0-9]+\.apps\.googleusercontent\.com$')


def read_dotenv(path):
    values = {}
    if not os.path.exists(path):
        return values
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith('#') or '=' not in line:
                continue
            key, val = line.split('=', 1)
            values[key.strip()] = val.strip().strip('"').strip("'")
    return values


def main():
    dotenv = read_dotenv(os.path.join(ROOT, '.env'))
    client_id = (os.environ.get('GOOGLE_CLIENT_ID') or dotenv.get('GOOGLE_CLIENT_ID') or '').strip()
    if client_id and not CLIENT_ID_RE.match(client_id):
        sys.exit('GOOGLE_CLIENT_ID does not look like a Google OAuth client ID '
                 '(expected something like 1234-abc.apps.googleusercontent.com). config.js was not written.')
    config = {'googleClientId': client_id}
    with open(os.path.join(ROOT, 'config.js'), 'w', encoding='utf-8') as f:
        f.write('/* Generated by scripts/make-config.py from .env or environment variables. Do not edit or commit. */\n')
        f.write('window.CF_CONFIG = ' + json.dumps(config) + ';\n')
    print('config.js written: Google Drive backup ' + ('ON' if client_id else 'OFF (no GOOGLE_CLIENT_ID set)'))


if __name__ == '__main__':
    main()
