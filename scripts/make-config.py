#!/usr/bin/env python3
"""Write config.js (the browser's settings) from environment variables.

Values come from real environment variables first (GitHub Actions passes the repository
variable this way), then from the local .env file. config.js is generated, so it is never
committed. Run from anywhere:  python3 scripts/make-config.py
"""
import hashlib
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CLIENT_ID_RE = re.compile(r'^[0-9]+-[a-z0-9]+\.apps\.googleusercontent\.com$')
GOATCOUNTER_RE = re.compile(r'^[a-z0-9][a-z0-9-]{1,48}$')
EMAIL_RE = re.compile(r'^[^@\s,]+@[^@\s,]+\.[^@\s,]+$')


def read_dotenv(path):
    values = {}
    if not os.path.exists(path):
        return values
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith('#') or '=' not in line:
                continue
            key, val = line.split('=', 1)
            values[key.strip()] = val.strip().strip('"').strip("'")
    return values


def main():
    dotenv = read_dotenv(os.path.join(ROOT, '.env'))
    env = lambda k: (os.environ.get(k) or dotenv.get(k) or '').strip()
    client_id = env('GOOGLE_CLIENT_ID')
    if client_id and not CLIENT_ID_RE.match(client_id):
        sys.exit('GOOGLE_CLIENT_ID does not look like a Google OAuth client ID '
                 '(expected something like 1234-abc.apps.googleusercontent.com). config.js was not written.')
    gc = env('GOATCOUNTER_CODE').lower()
    if gc and not GOATCOUNTER_RE.match(gc):
        sys.exit('GOATCOUNTER_CODE should be just the site code, e.g. "cashflow" for cashflow.goatcounter.com. config.js was not written.')
    # admins are stored only as SHA-256 fingerprints, so the published config.js never shows anyone's email
    admins = [a.strip().lower() for a in env('ADMIN_EMAILS').split(',') if a.strip()]
    bad = [a for a in admins if not EMAIL_RE.match(a)]
    if bad:
        sys.exit('ADMIN_EMAILS must be a comma-separated list of email addresses. config.js was not written.')
    config = {
        'googleClientId': client_id,
        'goatcounterCode': gc,
        'adminHashes': [hashlib.sha256(a.encode('utf-8')).hexdigest() for a in admins],
    }
    with open(os.path.join(ROOT, 'config.js'), 'w', encoding='utf-8') as f:
        f.write('/* Generated by scripts/make-config.py from .env or environment variables. Do not edit or commit. */\n')
        f.write('window.CF_CONFIG = ' + json.dumps(config) + ';\n')
    print('config.js written: Google sign-in ' + ('ON' if client_id else 'OFF')
          + ', usage counts ' + ('ON' if gc else 'OFF') + ', admins: ' + str(len(admins)))


if __name__ == '__main__':
    main()
